#!/usr/bin/env node
/**
 * Render the per-chain venue map.
 *
 *   node scripts/venueMap.js           # write docs/09-chain-venues.md + data/venue-map.json
 *   node scripts/venueMap.js --check   # exit 1 when the doc is stale (CI)
 *
 * This is documentation of absence, not of presence. A chain with no verified venue is the
 * state that used to be invisible: quotes returned null and nothing said why. The map makes
 * "no venue" a row you can see, and `--check` keeps it from drifting away from `chains.js`.
 *
 * Offline: it reads `src/config/chains.js` only. Verification evidence lives in
 * `output/venue-check.json` and is summarised when present, never required.
 */

const fs = require("fs");
const path = require("path");
const { CHAINS } = require("../src/config/chains");
const { venuesOf, VENUES } = require("../src/config/venues");

const ROOT = path.resolve(__dirname, "..");
const DOC = path.join(ROOT, "docs", "09-chain-venues.md");
const JSON_OUT = path.join(ROOT, "data", "venue-map.json");

function build() {
  const rows = Object.keys(CHAINS)
    .map((key) => {
      const chain = CHAINS[key];
      const { configured } = venuesOf(key);
      return {
        chain: key,
        name: chain.name,
        chainId: chain.chainId,
        explorer: chain.explorer || "",
        venues: configured,
        gaps: VENUES.filter((v) => !configured.includes(v)),
      };
    })
    .sort((a, b) => a.chainId - b.chainId);

  const withVenue = rows.filter((r) => r.venues.length);
  const without = rows.filter((r) => !r.venues.length);
  return { rows, withVenue, without };
}

function render({ rows, withVenue, without }) {
  const counts = {};
  for (const r of rows) for (const v of r.venues) counts[v] = (counts[v] || 0) + 1;

  const lines = [
    "# Chain venues",
    "",
    "<!-- Generated by `npm run docs:venues` from src/config/chains.js. Do not edit by hand. -->",
    "",
    `${rows.length} chains, **${withVenue.length} with at least one verified venue**, ${without.length} with none.`,
    "A venue is listed only when its factory answers the protocol's own ABI on that chain; code at",
    "the right address is not enough (11 chains carry a 2,109-byte stub at the Uniswap V3 factory",
    "address that answers nothing).",
    "",
    "| Venue | Chains |",
    "|---|---:|",
    ...Object.entries(counts)
      .sort((a, b) => b[1] - a[1])
      .map(([v, n]) => `| ${v} | ${n} |`),
    "",
    "## Chains with a venue",
    "",
    "| Chain | Id | Venues | Missing |",
    "|---|---:|---|---|",
    ...withVenue.map(
      (r) => `| ${r.name} | ${r.chainId} | ${r.venues.join(", ")} | ${r.gaps.join(", ") || "—"} |`
    ),
    "",
    "## Chains with no venue",
    "",
    "A quote like `simulate:*:fork` cannot run here. Add one only with on-chain evidence:",
    "`npm run chain:discover <chain>` prints what the canonical addresses answer.",
    "",
    "| Chain | Id | Explorer |",
    "|---|---:|---|",
    ...without.map((r) => `| ${r.name} | ${r.chainId} | ${r.explorer || "—"} |`),
    "",
  ];
  return lines.join("\n");
}

function main() {
  const built = build();
  const doc = render(built);
  const snapshot = {
    generatedAt: new Date().toISOString(),
    chains: built.rows.length,
    withVenue: built.withVenue.length,
    withoutVenue: built.without.length,
    rows: built.rows,
  };

  if (process.argv.includes("--check")) {
    const current = fs.existsSync(DOC) ? fs.readFileSync(DOC, "utf8") : "";
    if (current !== doc) {
      console.error("docs/09-chain-venues.md is stale — run `npm run docs:venues`");
      process.exit(1);
    }
    console.log(`venue map OK — ${built.withVenue.length}/${built.rows.length} chains have a venue`);
    return;
  }

  fs.mkdirSync(path.dirname(DOC), { recursive: true });
  fs.writeFileSync(DOC, doc);
  fs.writeFileSync(JSON_OUT, JSON.stringify(snapshot, null, 2) + "\n");
  console.log(
    `wrote docs/09-chain-venues.md and data/venue-map.json — ` +
      `${built.withVenue.length}/${built.rows.length} chains have a venue, ${built.without.length} have none`
  );
}

main();

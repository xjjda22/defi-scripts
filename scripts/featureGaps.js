#!/usr/bin/env node
/**
 * Feature x test matrix (docs/08-feature-test-gaps.md + data/feature-gaps.json).
 *
 *   npm run coverage:features          # regenerate both files
 *   npm run coverage:features:check    # fail on missing rows, unknown or unmapped scripts, stale files
 *
 * Source: src/catalog/protocolFeatures.js. Ranks come from showcase/data.json; the row set
 * that must be covered is the pinned snapshot data/coverage-snapshot.json.
 */

const fs = require("fs");
const path = require("path");
const { PROTOCOL_FEATURES } = require("../src/catalog/protocolFeatures");
const { PAUSED } = require("../src/catalog/forkStatus");

const ROOT = path.join(__dirname, "..");
const JSON_PATH = "data/feature-gaps.json";
const DOC_PATH = "docs/08-feature-test-gaps.md";

function readJson(rel) {
  try {
    return JSON.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));
  } catch {
    return null;
  }
}

function build() {
  const scripts = require("../package.json").scripts;
  const showcase = readJson("showcase/data.json") || { overall: [] };
  const snapshot = readJson("data/coverage-snapshot.json") || { forkable: [] };
  const rankOf = new Map(showcase.overall.map((row, i) => [row.id, i + 1]));
  const problems = [];
  const used = new Set();
  const protocols = PROTOCOL_FEATURES.map(entry => {
    const features = Object.entries(entry.features).map(([feature, spec]) => {
      for (const script of spec.scripts || []) {
        used.add(script);
        if (!scripts[script]) problems.push(`${entry.key}: "${feature}" references missing script ${script}`);
      }
      let status = spec.kind;
      if (status === "tested") {
        const forkScripts = spec.scripts.filter(s => s.startsWith("fork:"));
        status = forkScripts.length && forkScripts.every(s => PAUSED[s]) ? "failing-paused" : "direct";
      }
      return { feature, status, scripts: spec.scripts || [], note: spec.note || null };
    });
    const count = k => features.filter(f => f.status === k).length;
    return {
      key: entry.key,
      name: entry.name,
      rank: rankOf.get(entry.key) || null,
      pinned: snapshot.forkable.includes(entry.key),
      docs: entry.docs,
      counts: { features: features.length, direct: count("direct"), linked: count("linked"), failingPaused: count("failing-paused"), gap: count("gap"), notTestable: count("not-testable") },
      features,
    };
  });
  protocols.sort((a, b) => (a.rank || 9999) - (b.rank || 9999) || a.name.localeCompare(b.name));
  const keys = new Set(protocols.map(p => p.key));
  for (const id of snapshot.forkable) if (!keys.has(id)) problems.push(`pinned forkable row ${id} has no entry in src/catalog/protocolFeatures.js`);
  for (const script of Object.keys(scripts)) {
    if (script.startsWith("fork:") && script !== "fork:all" && !used.has(script)) problems.push(`${script} is not mapped to any feature`);
  }
  const sum = k => protocols.reduce((acc, p) => acc + p.counts[k], 0);
  const totals = { protocols: protocols.length, features: sum("features"), direct: sum("direct"), linked: sum("linked"), failingPaused: sum("failingPaused"), gap: sum("gap"), notTestable: sum("notTestable") };
  const gaps = [];
  for (const p of protocols) for (const f of p.features) if (f.status === "gap") gaps.push({ rank: p.rank, protocol: p.name, key: p.key, feature: f.feature, note: f.note });
  const data = { snapshot: snapshot.id || null, rankedFrom: showcase.generatedAt || null, totals, gaps, protocols };
  return { data, problems };
}

const cell = s => String(s == null ? "" : s).replace(/\|/g, "\\|");
const LABEL = { direct: "tested-direct", linked: "linked", "failing-paused": "failing-paused", gap: "**gap**", "not-testable": "not-testable" };

function renderDoc({ data }) {
  const { totals } = data;
  const out = [];
  out.push("# Feature test gaps (fork + simulation)");
  out.push("");
  out.push("Generated by `npm run coverage:features` from `src/catalog/protocolFeatures.js`. Do not edit by hand; `npm run catalog:check` fails when it is stale.");
  out.push("");
  out.push("Rule: every public, permissionless feature of every protocol is tested locally on an Anvil fork (a revert is a FAIL). This matrix is the playground routine's backlog: work the **Top gaps** list from the top.");
  out.push("");
  out.push(`Rows: pinned snapshot \`${data.snapshot}\` plus catalog protocols with fork tests. Ranks from the board built ${data.rankedFrom}.`);
  out.push("");
  out.push("| Protocols | Features | Tested-direct | Linked | Failing-paused | Gap | Not testable |");
  out.push("| --- | --- | --- | --- | --- | --- | --- |");
  out.push(`| ${totals.protocols} | ${totals.features} | ${totals.direct} | ${totals.linked} | ${totals.failingPaused} | ${totals.gap} | ${totals.notTestable} |`);
  out.push("");
  out.push("## Top gaps (priority order)");
  out.push("");
  out.push("Top-50 rank first, then rank order; within a protocol, the order its features are listed (most-used first).");
  out.push("");
  out.push("| # | Rank | Protocol | Feature | How to test |");
  out.push("| --- | --- | --- | --- | --- |");
  data.gaps.forEach((gap, i) => out.push(`| ${i + 1} | ${gap.rank || "-"} | ${cell(gap.protocol)} | ${cell(gap.feature)} | ${cell(gap.note)} |`));
  out.push("");
  out.push("## Per protocol");
  out.push("");
  for (const p of data.protocols) {
    out.push(`### ${p.rank ? `#${p.rank} ` : ""}${p.name}`);
    out.push("");
    out.push(`Docs: ${p.docs} · ${p.counts.direct}/${p.counts.features} tested-direct, ${p.counts.gap} gap, ${p.counts.notTestable} not testable`);
    out.push("");
    out.push("| Feature | Status | Scripts | Note |");
    out.push("| --- | --- | --- | --- |");
    for (const f of p.features) out.push(`| ${cell(f.feature)} | ${LABEL[f.status]} | ${f.scripts.map(s => `\`${s}\``).join(", ")} | ${cell(f.note)} |`);
    out.push("");
  }
  return out.join("\n");
}

function check() {
  const result = build();
  const problems = [...result.problems];
  const json = JSON.stringify(result.data, null, 2) + "\n";
  if (readText(JSON_PATH) !== json) problems.push(`${JSON_PATH} is stale (run npm run coverage:features)`);
  if (readText(DOC_PATH) !== renderDoc(result)) problems.push(`${DOC_PATH} is stale (run npm run coverage:features)`);
  return { problems, totals: result.data.totals };
}

function readText(rel) {
  try {
    return fs.readFileSync(path.join(ROOT, rel), "utf8");
  } catch {
    return null;
  }
}

function main() {
  if (process.argv.includes("--check")) {
    const { problems, totals } = check();
    if (problems.length) {
      console.error(`Feature gaps check failed (${problems.length}):`);
      for (const p of problems) console.error(`  - ${p}`);
      process.exit(1);
    }
    console.log(`Feature gaps OK: ${totals.features} features, ${totals.direct} tested, ${totals.gap} gaps, ${totals.notTestable} not testable.`);
    return;
  }
  const result = build();
  if (result.problems.length) {
    console.error(result.problems.join("\n"));
    process.exit(1);
  }
  fs.writeFileSync(path.join(ROOT, JSON_PATH), JSON.stringify(result.data, null, 2) + "\n");
  fs.writeFileSync(path.join(ROOT, DOC_PATH), renderDoc(result));
  console.log(`Wrote ${JSON_PATH} and ${DOC_PATH}:`, result.data.totals);
}

if (require.main === module) main();
module.exports = { build, check, renderDoc };

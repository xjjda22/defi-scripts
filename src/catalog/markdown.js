const { KINDS } = require("./catalog");
const { SECTIONS, featuresForSection } = require("./forkFeatures");

const DOC_PATH = "docs/02-protocol-catalog.md";
const README_START = "<!-- catalog:start -->";
const README_END = "<!-- catalog:end -->";

const cell = text => String(text).replace(/\|/g, "\\|");
const mark = n => (n ? (n > 1 ? `✓ ${n}` : "✓") : "");
const anchor = id => `p-${id.replace(/[^a-z0-9-]/g, "")}`;
const groupAnchor = id => `c-${id}`;
const README_PREVIEW = 6;
const link = (entry, base = "") => `[${entry.name}](${base}#${anchor(entry.id)})`;
const totalScripts = catalog => [...catalog.protocols, ...catalog.boards].reduce((n, e) => n + e.scripts.length, 0);

function grouped(catalog) {
  return catalog.categories.map(c => ({ ...c, entries: catalog.protocols.filter(p => p.category === c.id) }));
}

function commandTable(entry) {
  const rows = entry.scripts.map(s => `| \`npm run ${s.name}\` | ${s.kind} | ${cell(s.description || "")} |`);
  return ["| Command | Kind | What it does |", "|---|---|---|", ...rows].join("\n");
}

function card(entry, level) {
  const meta = [
    entry.url ? `[${entry.url.replace(/^https?:\/\/(www\.)?/, "").replace(/\/$/, "")}](${entry.url})` : null,
  ];
  if (entry.data && entry.data !== "—") meta.push(`Data: ${entry.data}`);
  meta.push(KINDS.filter(k => entry.kinds[k]).join(" · "));
  const lines = [`<a id="${anchor(entry.id)}"></a>`, "", `${"#".repeat(level)} ${entry.name}`, ""];
  lines.push(meta.filter(Boolean).join(" · "), "", entry.about, "");
  if (entry.notes?.length) {
    lines.push("> **Context**", ...entry.notes.flatMap(n => [">", `> ${n}`]), "");
  }
  lines.push(commandTable(entry), "");
  return lines.join("\n");
}

function allGroups(catalog) {
  const boards = catalog.boardGroups.map(g => ({ ...g, entries: catalog.boards.filter(b => b.group === g.id) }));
  return [...grouped(catalog), ...boards];
}

function categoryIndex(catalog, base = "", limit = Infinity) {
  const rows = allGroups(catalog).map(g => {
    const shown = g.entries.slice(0, limit).map(e => link(e, base));
    const rest = g.entries.length - shown.length;
    if (rest > 0) shown.push(`[+${rest} more](${base}#${groupAnchor(g.id)})`);
    return `| [${g.label}](${base}#${groupAnchor(g.id)}) | ${g.entries.length} | ${shown.join(" · ")} |`;
  });
  return ["| Category | Count | Entries |", "|---|---:|---|", ...rows].join("\n");
}

function coverageMatrix(catalog) {
  const head = `| Protocol | Category | ${KINDS.join(" | ")} |`;
  const sep = `|---|---|${KINDS.map(() => ":-:").join("|")}|`;
  const rows = grouped(catalog).flatMap(g =>
    g.entries.map(e => `| ${link(e)} | ${g.label} | ${KINDS.map(k => mark(e.kinds[k])).join(" | ")} |`)
  );
  return [head, sep, ...rows].join("\n");
}

function renderDoc(catalog) {
  const out = [
    "# Protocol catalog",
    "",
    "<!-- Generated by `npm run catalog:docs` from src/catalog/protocols.js + package.json. Do not edit by hand. -->",
    "",
    `${catalog.protocols.length} protocols and ${catalog.boards.length} cross-protocol boards/tools, ${totalScripts(catalog)} npm scripts. ` +
      "In a terminal, `npm run catalog` prints the same view and `npm run catalog -- <protocol>` prints one card.",
    "",
    "**Kinds:** *Analytics* prints a live snapshot. *Smoke* is a pass/fail check of the same data source (exit code ≠ 0 when it breaks). " +
      "*Simulate* quotes or replays on-chain (RPC or fork). *Swap* is a wallet-backed example. *Cross-chain* aggregates one protocol across chains (subgraphs).",
    "",
    "## Index",
    "",
    categoryIndex(catalog),
    "",
    "## Coverage matrix",
    "",
    coverageMatrix(catalog),
    "",
  ];
  for (const g of allGroups(catalog)) {
    out.push(`<a id="${groupAnchor(g.id)}"></a>`, "", `## ${g.label}`, "");
    for (const e of g.entries) out.push(card(e, 3));
  }
  return (
    out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

function renderReadmeSection(catalog) {
  return [
    README_START,
    "",
    `**${catalog.protocols.length} protocols**, **${catalog.boards.length} cross-protocol boards/tools**, **${totalScripts(catalog)} commands** (not counting repo tooling such as lint and reports). ` +
      `Each name links to its card in the [protocol catalog](${DOC_PATH}): every command, what it prints, and what it needs.`,
    "",
    categoryIndex(catalog, DOC_PATH, README_PREVIEW),
    "",
    README_END,
  ].join("\n");
}

function replaceReadmeSection(readme, catalog) {
  const start = readme.indexOf(README_START);
  const end = readme.indexOf(README_END);
  if (start === -1 || end === -1) throw new Error(`README is missing ${README_START} / ${README_END} markers`);
  return readme.slice(0, start) + renderReadmeSection(catalog) + readme.slice(end + README_END.length);
}

// --- Fork feature tables in docs/04-fork-testing.md -------------------------
// Generated from src/catalog/forkFeatures.js so the doc and the showcase panel
// cannot describe different behaviour.

const FORK_DOC_PATH = "docs/04-fork-testing.md";
const FEATURE_START = id => `<!-- features:${id} -->`;
const FEATURE_END = id => `<!-- /features:${id} -->`;
const COLUMN_HEADERS = { script: "Script", chain: "Chain", action: "Action", assertion: "Assertion" };

/**
 * One docs row per `group`, fanned back out into the individual scripts.
 * `fork:aave:supply` / `:borrow` when the whole group shares a protocol,
 * otherwise every name in full (`fork:base:deposit` / `fork:optimism:deposit`).
 */
function scriptCell(rows) {
  const protocol = script => script.split(":")[1];
  const shared = rows.every(row => protocol(row.script) === protocol(rows[0].script));
  return rows
    .map((row, index) => {
      if (index === 0) return `\`${row.script}\``;
      return shared ? `\`:${row.script.split(":").slice(2).join(":")}\`` : `\`${row.script}\``;
    })
    .join(" / ");
}

/**
 * Merge consecutive registry entries that share a `group` into one docs row.
 * A run is only merged while every non-script cell is identical, so grouping can
 * never hide a differing action or assertion the way a naive merge would.
 */
function groupRuns(rows, columns) {
  const shared = row => columns.filter(col => col !== "script").map(col => String(row[col] == null ? "" : row[col])).join("\u0000");
  const runs = [];
  for (const row of rows) {
    const last = runs[runs.length - 1];
    if (row.group && last && last.group === row.group && last.shared === shared(row)) {
      last.rows.push(row);
      continue;
    }
    runs.push({ group: row.group || null, shared: shared(row), rows: [row] });
  }
  return runs;
}

const chainLabel = chain => (chain ? chain.charAt(0).toUpperCase() + chain.slice(1) : "");

function renderFeatureTable(section) {
  const header = section.columns.map(col =>
    col === "assertion" && section.assertionHeader ? section.assertionHeader : COLUMN_HEADERS[col]
  );
  const lines = [`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`];
  for (const run of groupRuns(featuresForSection(section.id), section.columns)) {
    const first = run.rows[0];
    const cells = section.columns.map(col => {
      if (col === "script") return scriptCell(run.rows);
      if (col === "chain") return chainLabel(first[col]);
      return cell(first[col] == null ? "" : first[col]);
    });
    lines.push(`| ${cells.join(" | ")} |`);
  }
  return lines.join("\n");
}

/** Replace every marked feature table block in docs/04 with generated content. */
function replaceForkFeatureTables(doc) {
  let out = doc;
  for (const section of SECTIONS) {
    const start = out.indexOf(FEATURE_START(section.id));
    const end = out.indexOf(FEATURE_END(section.id));
    if (start === -1 || end === -1) {
      throw new Error(`${FORK_DOC_PATH} is missing ${FEATURE_START(section.id)} / ${FEATURE_END(section.id)} markers`);
    }
    const block = `${FEATURE_START(section.id)}\n${renderFeatureTable(section)}\n`;
    out = out.slice(0, start) + block + out.slice(end);
  }
  return out;
}

module.exports = {
  DOC_PATH,
  FORK_DOC_PATH,
  renderDoc,
  replaceReadmeSection,
  renderFeatureTable,
  replaceForkFeatureTables,
};
